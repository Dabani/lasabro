/** A frontend package that declares itself a LASABRO web plugin in its package.json: `"lasabro": { "plugin": "Lasabro.Hr", "frontend": "react" }`. */
export interface WebPluginPackage {
  /** npm package name, for example `@lasabro/hr-react` */
  name: string;
  /** Plugin id, `Lasabro.Hr` */
  plugin: string;
  frontend: string;
}

/**
 * Finds web plugins among the dependencies of a host app. `read` returns the parsed package.json of a package, or undefined
 * when it cannot be found; it is injected so this stays free of file-system code (the CLI supplies the real reader).
 */
export function discoverWebPlugins(
  dependencies: readonly string[],
  read: (pkg: string) => Record<string, unknown> | undefined,
  frontend: string,
): WebPluginPackage[] {
  const found: WebPluginPackage[] = [];
  for (const name of [...dependencies].sort()) {
    const meta = read(name)?.lasabro as { plugin?: unknown; frontend?: unknown } | undefined;
    if (!meta || typeof meta.plugin !== 'string' || meta.frontend !== frontend) continue;
    if (!/^[A-Z][A-Za-z0-9]*\.[A-Z][A-Za-z0-9]*$/.test(meta.plugin)) continue;
    found.push({ name, plugin: meta.plugin, frontend });
  }
  return found;
}

const identifier = (id: string) => id.replace(/[^A-Za-z0-9]/g, '_').replace(/^(\d)/, '_$1');

/**
 * Source of the generated registry module. Static imports are what a bundler needs to split code, so the list is
 * written to a file at build time (`lasabro-web-sync`) instead of being discovered at run time.
 */
export function generateRegistrySource(plugins: readonly WebPluginPackage[]): string {
  const lines = [
    '// Generated by `lasabro-web-sync`. Do not edit: run it again after adding or removing a web plugin.',
    "import type { PluginDefinition } from '@lasabro/kit';",
  ];
  for (const p of plugins) lines.push(`import ${identifier(p.plugin)} from '${p.name}';`);
  lines.push('', `// eslint-disable-next-line @typescript-eslint/no-explicit-any`);
  lines.push(`export const plugins: PluginDefinition<any>[] = [${plugins.map((p) => identifier(p.plugin)).join(', ')}];`, '');

  return lines.join('\n');
}
