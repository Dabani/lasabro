import { describe, expect, it } from 'vitest';
import { discoverWebPlugins, generateRegistrySource } from '../src';

const packages: Record<string, Record<string, unknown>> = {
  '@lasabro/hr-react': { lasabro: { plugin: 'Lasabro.Hr', frontend: 'react' } },
  '@lasabro/hr-vue': { lasabro: { plugin: 'Lasabro.Hr', frontend: 'vue' } },
  '@lasabro/payroll-react': { lasabro: { plugin: 'Lasabro.Payroll', frontend: 'react' } },
  '@lasabro/broken-react': { lasabro: { plugin: 'not-an-id', frontend: 'react' } },
  react: { name: 'react' },
};
const read = (name: string) => packages[name];

describe('discoverWebPlugins', () => {
  it('keeps only valid plugins of the requested frontend flavour, sorted by package name', () => {
    const found = discoverWebPlugins(['react', '@lasabro/payroll-react', '@lasabro/hr-vue', '@lasabro/hr-react', '@lasabro/broken-react', 'missing'], read, 'react');
    expect(found).toEqual([
      { name: '@lasabro/hr-react', plugin: 'Lasabro.Hr', frontend: 'react' },
      { name: '@lasabro/payroll-react', plugin: 'Lasabro.Payroll', frontend: 'react' },
    ]);
  });
});

describe('generateRegistrySource', () => {
  it('writes static imports and an array', () => {
    const src = generateRegistrySource([{ name: '@lasabro/hr-react', plugin: 'Lasabro.Hr', frontend: 'react' }]);
    expect(src).toContain("import Lasabro_Hr from '@lasabro/hr-react';");
    expect(src).toContain('export const plugins: PluginDefinition<any>[] = [Lasabro_Hr];');
    expect(src).toContain('Generated by `lasabro-web-sync`');
  });

  it('writes an empty registry when there are no web plugins', () => {
    expect(generateRegistrySource([])).toContain('export const plugins: PluginDefinition<any>[] = [];');
  });
});
