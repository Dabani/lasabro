<?php

namespace Lasabro\Framework\Console;

use Lasabro\Framework\Plugin\PluginManager;

class PluginDocsCommand extends PluginCommand
{
    protected $signature = 'lasabro:plugin:docs {--write : Write docs/DEPENDENCIES.md into each plugin folder instead of printing}';
    protected $description = 'Generate the dependency notice of every plugin from its manifest';

    public function handle(PluginManager $pm): int
    {
        return $this->guarded($pm, function (PluginManager $pm) {
            $resolver = $pm->resolver();
            foreach ($pm->manifests() as $id => $m) {
                $lines = ["# {$m->title} ({$id})", '', '> Generated by `php artisan lasabro:plugin:docs` from composer.json. Edit the manifest, not this file.', ''];
                $lines[] = '## Requires';
                $lines[] = '';
                if ($m->requires) {
                    foreach ($m->requires as $dep => $constraint) {
                        $lines[] = "- **{$dep}** `{$constraint}`";
                    }
                    $lines[] = '';
                    $lines[] = "**Notice:** {$id} cannot be activated unless " . implode(', ', array_keys($m->requires)) . ' are installed and active.';
                } else {
                    $lines[] = 'No other plugin is required.';
                }
                if ($m->suggests) {
                    $lines[] = '';
                    $lines[] = '## Works better with';
                    $lines[] = '';
                    foreach ($m->suggests as $dep => $why) {
                        $lines[] = "- **{$dep}**" . ($why !== '' ? ": {$why}" : '');
                    }
                }
                if ($by = $resolver->dependentsOf($id)) {
                    $lines[] = '';
                    $lines[] = '## Required by';
                    $lines[] = '';
                    foreach ($by as $other) {
                        $lines[] = "- {$other}";
                    }
                }
                $text = implode("\n", $lines) . "\n";
                if ($this->option('write')) {
                    @mkdir($m->path . '/docs', 0775, true);
                    file_put_contents($m->path . '/docs/DEPENDENCIES.md', $text);
                    $this->line("wrote {$m->path}/docs/DEPENDENCIES.md");
                } else {
                    $this->line($text);
                }
            }

            return self::SUCCESS;
        });
    }
}
