<?php

declare(strict_types=1);

namespace Lasabro\Framework\Plugin;

/**
 * Compiled list of the plugins to boot, in dependency order (like config:cache). Reading it needs no database,
 * so boot is cheap and works before the first migration.
 */
final class PluginCache
{
    /** @param list<array{id:string,provider:string,path:string}> $entries */
    public function write(string $file, array $entries): void
    {
        $dir = dirname($file);
        if (! is_dir($dir) && ! mkdir($dir, 0775, true) && ! is_dir($dir)) {
            throw new PluginException("Cannot create {$dir}.");
        }
        $php = "<?php\n\n// Generated by the lasabro:plugin:* commands. Do not edit; rebuild with `php artisan lasabro:plugin:discover`.\nreturn "
            . var_export(['plugins' => array_values($entries)], true) . ";\n";
        $tmp = $file . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($tmp, $php) === false || ! rename($tmp, $file)) {
            @unlink($tmp);
            throw new PluginException("Cannot write {$file}.");
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($file, true);
        }
    }

    /** @return list<array{id:string,provider:string,path:string}> empty when there is no cache */
    public function read(string $file): array
    {
        if (! is_file($file)) {
            return [];
        }
        $data = require $file;

        return is_array($data) && isset($data['plugins']) && is_array($data['plugins']) ? array_values($data['plugins']) : [];
    }

    public function forget(string $file): void
    {
        if (is_file($file)) {
            unlink($file);
        }
    }
}
